import subprocess, sys, os, time, asyncio
from playwright.async_api import async_playwright
HERE=os.path.dirname(os.path.abspath(__file__))
FAILS=[]
def ok(c,m):
    print(("OK   " if c else "FAIL ")+m)
    if not c: FAILS.append(m)
SDK=open(os.path.join(HERE,"fake_sdk.js"),encoding="utf-8").read()
env=dict(os.environ,ALS_VAPID="BTESTKEY123")
subprocess.run([sys.executable,os.path.join(HERE,"build.py"),os.path.join(HERE,"dist_push")],check=True,env=env,stdout=subprocess.DEVNULL)
async def main():
    srv=subprocess.Popen([sys.executable,"-m","http.server","8766","--bind","127.0.0.1"],cwd=os.path.join(HERE,"dist_push"),stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
    time.sleep(1)
    try:
        async with async_playwright() as pw:
            b=await pw.chromium.launch()
            ctx=await b.new_context(viewport={"width":390,"height":780},permissions=["notifications"],bypass_csp=True)
            await ctx.route("**/fonts.g*/**",lambda r:r.abort())
            page=await ctx.new_page(); errs=[]
            page.on("pageerror",lambda e:errs.append(str(e)))
            await page.add_init_script(SDK)
            await page.add_init_script("(()=>{let p=sessionStorage.getItem('np')||'default';Object.defineProperty(Notification,'permission',{get:()=>p});Notification.requestPermission=async()=>{p='granted';sessionStorage.setItem('np',p);return p}})()")
            await page.add_init_script("Object.defineProperty(navigator.serviceWorker,'ready',{get:()=>Promise.resolve({showNotification:(t,o)=>{window.__shown=[t,o.body];return Promise.resolve()}})})")
            await page.goto("http://localhost:8766/app.html")
            await page.wait_for_selector("#lgForm:not([hidden])")
            await page.fill("#lgMail","a@x.fr"); await page.fill("#lgPass","good"); await page.click("#lgGo")
            await page.wait_for_function('document.getElementById("syncT").textContent==="Synchronisé"',timeout=8000)
            await page.click("#bkBtn"); await page.wait_for_timeout(300)
            ok(await page.locator("#stPushBox").is_visible(),"section Notifications visible dans Réglages")
            ok("Activer" in await page.inner_text("#stPush"),"bouton « Activer »")
            ok("1 h avant" in await page.inner_text("#stPushT"),"texte explicatif")
            await page.click("#stPush"); await page.wait_for_timeout(500)
            ok("Désactiver" in await page.inner_text("#stPush"),"après activation : bouton « Désactiver »")
            ok(await page.evaluate("Object.keys(window.__fbdb.devices||{}).length")==1,"jeton enregistré dans Firestore (devices)")
            ok(await page.evaluate("Object.values(window.__fbdb.devices)[0].uid")=="U1","jeton rattaché à l'utilisateur")
            ok(await page.locator("#stPushTest").is_visible(),"bouton Tester visible")
            await page.click("#stPushTest"); await page.wait_for_timeout(300)
            tst=await page.evaluate("Object.values(window.__fbdb.outbox||{}).filter(o=>o.kind==='test')")
            ok(len(tst)==1 and tst[0]["to"]=="self" and tst[0]["by"]=="U1" and tst[0]["sent"] is False,"bouton Tester : vrai message de test pour ses propres appareils (outbox)")
            # --- messages sortants (outbox) ---
            await page.click("#stClose")
            await page.evaluate("goMode('planning')"); await page.wait_for_timeout(200); await page.click("#fab")
            await page.fill("#rvWhat","Peugeot 208 clé"); await page.fill("#rvTime","14:30"); await page.click("#rvSave"); await page.wait_for_timeout(500)
            ob=await page.evaluate("Object.values(window.__fbdb.outbox||{}).filter(o=>o.kind!=='test')")
            ok(len(ob)==1 and ob[0]["kind"]=="rdv" and ob[0]["sent"] is False and ob[0]["to"]=="others" and ob[0]["by"]=="U1","nouveau RDV -> message pour l'associé dans outbox")
            ok("Nouveau RDV" in ob[0]["title"] and "Peugeot 208" in ob[0]["body"],"texte du message RDV")
            await page.click("#navStock"); await page.wait_for_timeout(300)
            names=await page.evaluate("Object.entries(window.__fbdb.items).filter(([k,v])=>v.section==='lame_m').map(([k,v])=>k+':'+v.name+':'+v.qty)")
            print("items",names)
            nm="TOY48"
            await page.evaluate("bump(items.find(i=>i.name==='TOY48'),3)"); await page.wait_for_timeout(1500)
            ok(await page.evaluate("items.find(i=>i.name==='TOY48').qty")==8,"stock monté à 8")
            ok(len(await page.evaluate("Object.values(window.__fbdb.outbox||{}).filter(o=>o.kind==='stock')"))==0,"monter le stock ne prévient pas")
            for k in range(0,8):
                await page.evaluate("bump(items.find(i=>i.name==='TOY48'),-1)"); await page.wait_for_timeout(900)
            st=await page.evaluate("Object.values(window.__fbdb.outbox||{}).filter(o=>o.kind==='stock')")
            ok(len(st)==1 and st[0]["to"]=="all" and nm in st[0]["title"],"stock bas : un seul message quand le seuil est franchi")
            ok(len(await page.evaluate("Object.values(window.__fbdb.outbox||{}).filter(o=>o.kind==='stock')"))==1,"pas de répétition en descendant plus bas")
            await page.reload(); await page.wait_for_function('document.getElementById("syncT").textContent==="Synchronisé"',timeout=8000)
            await page.click("#bkBtn"); await page.wait_for_timeout(300)
            ok("Désactiver" in await page.inner_text("#stPush"),"état « activé » mémorisé après rechargement")
            # --- réparation automatique de l'abonnement à l'ouverture ---
            tok0=await page.evaluate("localStorage.getItem('als-push-token')")
            # 1) le robot a noté un envoi réussi : affiché dans Réglages, et conservé par le contrôle à l'ouverture
            await page.wait_for_timeout(600)
            await page.evaluate("(t)=>{const d=JSON.parse(localStorage.getItem('__fbdb'));d.devices[t].okAt=Date.UTC(2026,10,10,13,36);localStorage.setItem('__fbdb',JSON.stringify(d))}",tok0)
            await page.reload(); await page.wait_for_function('document.getElementById("syncT").textContent==="Synchronisé"',timeout=8000)
            await page.wait_for_timeout(7000)
            ok(await page.evaluate("(t)=>!!window.__fbdb.devices[t].okAt",tok0),"contrôle à l'ouverture : la fiche de l'appareil garde sa trace d'envoi")
            await page.click("#bkBtn"); await page.wait_for_timeout(400)
            ok("Dernier envoi vers cet appareil" in await page.inner_text("#stPushT"),"Réglages : date du dernier envoi affichée")
            await page.click("#stClose")
            # 2) le système a changé le jeton en silence : la nouvelle fiche remplace l'ancienne
            await page.wait_for_timeout(600)
            await page.evaluate("localStorage.setItem('__tokn','neuf01')")
            await page.reload(); await page.wait_for_function('document.getElementById("syncT").textContent==="Synchronisé"',timeout=8000)
            await page.wait_for_timeout(7500)
            ks=await page.evaluate("Object.keys(window.__fbdb.devices||{})")
            ok(ks==["TOK_neuf01"] and await page.evaluate("localStorage.getItem('als-push-token')")=="TOK_neuf01","jeton renouvelé : réenregistré tout seul, ancien supprimé")
            # 3) le robot a supprimé la fiche (jeton refusé) : l'appli redemande un jeton et se réinscrit
            await page.wait_for_timeout(600)
            await page.evaluate("()=>{const d=JSON.parse(localStorage.getItem('__fbdb'));d.devices={};localStorage.setItem('__fbdb',JSON.stringify(d))}")
            await page.reload(); await page.wait_for_function('document.getElementById("syncT").textContent==="Synchronisé"',timeout=8000)
            await page.wait_for_timeout(7500)
            ok(await page.evaluate("Object.keys(window.__fbdb.devices||{}).length")==1 and await page.evaluate("window.__fblog.includes('deltoken')"),"fiche supprimée par le robot : réinscription automatique")
            await page.click("#bkBtn"); await page.wait_for_timeout(400)
            ok("Désactiver" in await page.inner_text("#stPush"),"toujours « activé » après réparation")
            await page.click("#stPush"); await page.wait_for_timeout(500)
            ok("Activer" in await page.inner_text("#stPush"),"désactivation : bouton revient à « Activer »")
            ok(await page.evaluate("Object.keys(window.__fbdb.devices||{}).length")==0,"jeton supprimé de Firestore")
            ok(not errs,"aucune erreur JS "+str(errs))
            await b.close()
        # sans clé : message "pas encore configurées"
        subprocess.run([sys.executable,os.path.join(HERE,"build.py"),os.path.join(HERE,"dist_push")],check=True,env=dict(os.environ,ALS_VAPID="-"),stdout=subprocess.DEVNULL)
        async with async_playwright() as pw:
            b=await pw.chromium.launch(); ctx=await b.new_context(viewport={"width":390,"height":780},bypass_csp=True)
            await ctx.route("**/fonts.g*/**",lambda r:r.abort())
            page=await ctx.new_page(); await page.add_init_script(SDK)
            await page.goto("http://localhost:8766/app.html"); await page.wait_for_selector("#lgForm:not([hidden])")
            await page.fill("#lgMail","a@x.fr"); await page.fill("#lgPass","good"); await page.click("#lgGo")
            await page.wait_for_function('document.getElementById("syncT").textContent==="Synchronisé"',timeout=8000)
            await page.click("#bkBtn"); await page.wait_for_timeout(300)
            ok("pas encore configurées" in await page.inner_text("#stPushT"),"sans clé serveur : message clair, bouton grisé")
            ok(await page.locator("#stPush").is_disabled(),"bouton désactivé sans clé")
            await b.close()
    finally:
        srv.terminate()
    print("ÉCHECS:",FAILS if FAILS else "aucun"); sys.exit(1 if FAILS else 0)
asyncio.run(main())
